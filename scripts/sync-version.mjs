import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { updateGeneratedFiles } from './generated-files.mjs';

export async function versionArtifacts() {
  const { version } = JSON.parse(await readFile('package.json', 'utf8'));
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
    throw new Error('package.json must contain a semantic version.');
  }
  const manifestPath = 'plugins/codex-dsh-trace/.codex-plugin/plugin.json';
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  manifest.version = version;
  const files = new Map([
    [manifestPath, JSON.stringify(manifest, null, 2) + '\n'],
    [
      'src/version.js',
      `// Generated by scripts/sync-version.mjs. Do not edit.\nexport const VERSION = ${JSON.stringify(version)};\n`,
    ],
    [
      'plugins/codex-dsh-trace/server/_version.py',
      `# Generated by scripts/sync-version.mjs. Do not edit.\nVERSION = ${JSON.stringify(version)}\n`,
    ],
  ]);
  return { version, files };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { version, files } = await versionArtifacts();
  await updateGeneratedFiles(files, { check: process.argv.includes('--check') });
  console.log(`Version metadata: ${version}`);
}
